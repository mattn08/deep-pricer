"""Generate high-precision reference prices for the analytic tests.

Published tables give a dozen points to four decimals. This gives as many points
as you want, to more digits than a double can hold, from a script that is itself
reviewable — so the reference is reproducible rather than transcribed.

The output is deliberately *not* committed by this script's author. Generate it,
spot-check several rows against Haug or Hull by hand, and commit it yourself. Two
independent wrong implementations agreeing is the failure mode this is meant to
avoid, and it is only avoided if a human checks the seam.

Usage:
    python python/tools/gen_reference.py --out cpp/tests/data
"""

from __future__ import annotations

import argparse
import csv
import datetime
import sys
from pathlib import Path
from typing import Iterator, NamedTuple

try:
    from mpmath import mp
except ImportError:  # pragma: no cover - dependency hint
    sys.exit("mpmath is required: pip install mpmath")


class Case(NamedTuple):
    """One row of the parameter grid, in the cost-of-carry convention."""

    label: str
    S: float
    K: float
    T: float
    r: float
    b: float
    sigma: float


def norm_cdf(x: mp.mpf) -> mp.mpf:
    """Standard normal CDF, evaluated at the working precision.

    erfc rather than a polynomial approximation: at 50 digits the difference is
    the whole point of generating this table.
    """
    return mp.erfc(-x / mp.sqrt(2)) / 2


def black_scholes_call(S: mp.mpf, K: mp.mpf, T: mp.mpf, r: mp.mpf, b: mp.mpf, sigma: mp.mpf):
    """Generalised Black-Scholes call, cost-of-carry form.

    b = r for a non-dividend stock, b = r - q with a continuous yield, b = 0 for
    a future. Same convention as Haug, which is what the barrier formulas use.
    """
    if T <= 0 or sigma <= 0:
        raise ValueError("degenerate case: handle T <= 0 and sigma <= 0 explicitly")
    vol_sqrt_t = sigma * mp.sqrt(T)
    d1 = (mp.log(S / K) + (b + sigma**2 / 2) * T) / vol_sqrt_t
    d2 = d1 - vol_sqrt_t
    return S * mp.e ** ((b - r) * T) * norm_cdf(d1) - K * mp.e ** (-r * T) * norm_cdf(d2)


def grid() -> Iterator[Case]:
    """A deliberately awkward parameter grid.

    Spans moneyness, maturity and volatility, and includes the corners where a
    double-precision implementation loses accuracy: deep out-of-the-money, very
    short maturity, very low and very high volatility.
    """
    spots = [60.0, 90.0, 100.0, 110.0, 150.0]
    maturities = [0.01, 0.25, 1.0, 5.0]
    vols = [0.05, 0.20, 0.60]
    rates = [0.0, 0.05]
    for S in spots:
        for T in maturities:
            for sigma in vols:
                for r in rates:
                    yield Case(
                        label=f"S={S:g},T={T:g},sigma={sigma:g},r={r:g}",
                        S=S,
                        K=100.0,
                        T=T,
                        r=r,
                        b=r,
                        sigma=sigma,
                    )


def write_table(path: Path, dps: int) -> int:
    generated = datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds")
    source = f"gen_reference.py mpmath dps={dps}"

    rows = []
    for case in grid():
        price = black_scholes_call(
            mp.mpf(case.S),
            mp.mpf(case.K),
            mp.mpf(case.T),
            mp.mpf(case.r),
            mp.mpf(case.b),
            mp.mpf(case.sigma),
        )
        rows.append(
            {
                "source": source,
                "label": case.label,
                "S": repr(case.S),
                "K": repr(case.K),
                "T": repr(case.T),
                "r": repr(case.r),
                "b": repr(case.b),
                "sigma": repr(case.sigma),
                # Rounded to a double on the way out; the extra digits mpmath
                # carried are what make that last digit trustworthy.
                "expected": repr(float(price)),
                # Tight, because this reference is exact to far beyond double
                # precision. Loosen only with a reason, and record the reason.
                "rel_tolerance": "1e-12",
                # Absolute floor for prices near zero, where relative error is
                # dominated by cancellation rather than by the formula.
                "abs_tolerance": "1e-14",
            }
        )

    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        handle.write(f"# generated by python/tools/gen_reference.py at {generated}\n")
        handle.write(f"# mpmath working precision: {dps} decimal digits\n")
        handle.write("# spot-check rows against a published table before trusting this file\n")
        writer = csv.DictWriter(handle, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)
    return len(rows)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=Path("cpp/tests/data"))
    parser.add_argument("--dps", type=int, default=50, help="mpmath working precision")
    args = parser.parse_args()

    mp.dps = args.dps

    written = write_table(args.out / "black_scholes_call.csv", args.dps)
    print(f"wrote {written} rows to {args.out / 'black_scholes_call.csv'}")

    # The barrier generator is deliberately absent. Reiner-Rubinstein term
    # assembly - the eta/phi sign conventions - is exactly what Step 2 exists to
    # get right, and a reference written by someone else removes the independence
    # that makes it ground truth. Add up_and_out_call here once you have written
    # and checked your own, so the two are genuinely independent.


if __name__ == "__main__":
    main()
